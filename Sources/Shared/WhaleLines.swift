    /// 有取件码时：10 次里至少 7 次报数；否则闲聊
    public static func speak(pendingCount: Int, transitCount: Int) -> String {
        let hasCode = pendingCount > 0
        let report = hasCode && Int.random(in: 0..<10) < 7
        let pool: [String]
        if report {
            let withNum = all.filter { $0.contains("%d") }
            pool = withNum.isEmpty ? all : withNum
        } else if pendingCount == 0 && transitCount > 0 {
            let transitish = all.filter { $0.contains("%d") || $0.contains("路") || $0.contains("等") }
            pool = transitish.isEmpty ? all : transitish
        } else {
            pool = all
        }
        let line = pool.randomElement() ?? "人家在看着快递哦"
        let n = report ? pendingCount : (pendingCount > 0 ? pendingCount : max(transitCount, 1))
        return line.replacingOccurrences(of: "%d", with: "\(n)")
    }

    public static func random() -> String {
        all.randomElement() ?? "人家在看着快递哦"
    }
